"""Second layer: virtual sensors defined in IFC models -> ``transform`` inputs.

Two steps, both needing the optional ``ifcopenshell`` dependency:

1. :func:`build_reference` (once per as-planned model): derive the bridge
   frame and the girder section of the cantilever from the superstructure IFC
   ("STB") and store them in the package (``data/bridge_frame.json``,
   ``data/ifc_girder.npz``), so that later mappings do not need the 9 MB file;
2. :func:`virtual_sensors_from_ifc`: read the sensor proxies of a sensor IFC
   (e.g. MKP's "DZ-Sim … TUS" model), map them into model coordinates and
   return the ``virtual_sensors`` list for :func:`~nibelungen_virtual_sensors.transform`.

Command line::

    python -m nibelungen_virtual_sensors.ifc reference STB.ifc
    python -m nibelungen_virtual_sensors.ifc sensors TUS.ifc [-o virtual_sensors.json]
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

import numpy as np

from .frame import BridgeFrame, frame_from_superstructure
from .mapping import map_sensor
from .section import SectionProbe

log = logging.getLogger(__name__)

def _data(name: str) -> Path:
    from ..transform import _data_path

    return _data_path(name)


def build_reference(structure_ifc: str, out_dir: str | None = None) -> BridgeFrame:
    """Derive frame + cantilever girder section from the superstructure IFC."""
    from ..transform import load_ifc_config
    from .reader import read_superstructure

    cfg = load_ifc_config()
    st = cfg["structure"]
    tris = read_superstructure(structure_ifc, st)
    verts = {k: v.reshape(-1, 3) for k, v in tris.items()}
    frame = frame_from_superstructure(verts, st["pier_head"], st["cantilever"], cfg["frame"],
                                      source=Path(structure_ifc).name)
    girder = np.concatenate([tris[st["pier_head"]], tris[st["cantilever"]]])
    sec = frame.to_section(girder.reshape(-1, 3)).reshape(-1, 3, 3)
    out = Path(out_dir) if out_dir else _data("")
    frame.save(out / "bridge_frame.json")
    np.savez_compressed(out / "ifc_girder.npz", triangles=sec, source=np.array(frame.source))
    log.info("bridge frame and %d girder triangles written to %s", len(sec), out)
    return frame


def model_probe() -> SectionProbe:
    """Boundary of the simulation mesh as a section probe (a, v, z) = (x, y, z)."""
    from ..transform import load_model_config

    with np.load(_data(load_model_config()["mesh_file"])) as d:
        return SectionProbe(d["points"][d["facets"]])


def _output_name(sensor: dict, cfg: dict) -> str:
    """Channel name for the predicted value: the 'Endwert' channel of the proxy."""
    chans = sensor["channels"]
    end = [c for c in chans if c.get(cfg["output_channel_property"]) == cfg["output_channel_value"]]
    return (end or chans)[0][cfg["channel_name_property"]] if chans else sensor["object_name"]


def virtual_sensors_from_ifc(sensor_ifc: str, frame_json: str | None = None,
                             girder_npz: str | None = None) -> list[dict]:
    """Virtual-sensor definitions (model coordinates) for every sensor proxy of an IFC file."""
    from ..transform import load_ifc_config
    from .reader import read_sensors

    cfg = load_ifc_config()
    frame = BridgeFrame.load(Path(frame_json) if frame_json else _data("bridge_frame.json"), cfg["frame"])
    with np.load(Path(girder_npz) if girder_npz else _data("ifc_girder.npz")) as d:
        ifc_probe = SectionProbe(d["triangles"])
    mprobe = model_probe()

    out = []
    for s in read_sensors(sensor_ifc, cfg["sensor_ifc"]):
        if s["quantity"] is None:
            log.warning("skipping %s: unsupported physical quantity", s["object_name"])
            continue
        m = map_sensor(s, frame, ifc_probe, mprobe, cfg)
        entry = {
            "name": _output_name(s, cfg["sensor_ifc"]),
            "quantity": s["quantity"],
            "position": m["position"],
        }
        entry["ifc"] = {
            "file": Path(sensor_ifc).name,
            "global_id": s["global_id"],
            "object_name": s["object_name"],
            "channels": [c.get(cfg["sensor_ifc"]["channel_name_property"]) for c in s["channels"]],
            "position_text": s["position_text"],
            "measuring_axis": s["measuring_axis"],
            "centroid_world": [round(c, 4) for c in s["centroid"]],
        }
        entry["mapping"] = m["mapping"]
        out.append(entry)
    return out


def write_sensor_file(sensors: list[dict], path: str, source: str) -> None:
    doc = {
        "_note": "Generated by `python -m nibelungen_virtual_sensors.ifc sensors`; "
                 "positions in simulation model coordinates [m], see README.",
        "source_ifc": source,
        "sensors": sensors,
    }
    Path(path).write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
